import test from 'node:test';
import assert from 'node:assert/strict';
import { generateWorld } from '../src/world.js';
import { Simulation } from '../src/simulation.js';
import { standable } from '../server/navigation/pathfinder.js';
import { IdleBehavior } from '../server/tasks/idle.js';
import { PERSONAS, Companion } from '../server/companion.js';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Room } from '../server/room.js';
import { WorldChat } from '../server/chat.js';
import { goalsFor, GOAL_LIMIT, parseReflection } from '../server/goals.js';
const ground=(w,x,z)=>{for(let y=46;y>0;y--){const p={x:x+.5,y,z:z+.5};if(standable(w,p)&&![5,6].includes(w.get(x,y-1,z)))return p;}};
const world=generateWorld(),seeded=(seed=5)=>()=>(seed=(seed*16807)%2147483647)/2147483647;
const scene=(phase)=>({world,simulation:new Simulation(world),phase});
const codexLife=(room,e)=>{const p=PERSONAS.codex;return new IdleBehavior(room,e,{home:ground(world,Math.floor(p.home.x),Math.floor(p.home.z)),night:p.night,lookOut:p.lookOut,lines:p.lines,nightLines:p.nightLines,homeLine:p.homeLine,nightLine:p.nightLine,random:seeded()});};
const run=(room,idle,seconds)=>{for(let i=0;i<60*seconds;i++){idle.tick(1/60);room.simulation.tick(1/60);}};
test('Codex lives at its dock and keeps a night shift instead of sleeping',()=>{
 const room=scene(.76),e=room.simulation.spawn('codex-companion');e.position=ground(world,26,28);
 const idle=codexLife(room,e);assert.equal(PERSONAS.codex.resident,true);
 run(room,idle,40);
 assert.ok(Math.hypot(e.position.x-idle.home.x,e.position.z-idle.home.z)<1.6,'back at the dock after dark');
 assert.ok(e.direction.x<-.5,'looking out west over the edge');
 const visitor=room.simulation.spawn('pat');visitor.position={...idle.home,x:idle.home.x+2};run(room,idle,1);
 assert.equal(e.gesture?.kind,'nod','awake: nods at a night visitor');assert.ok(PERSONAS.codex.nightLines.includes(e.speech),'with a night-shift line');
});
test('a first hello comes with a wave; each companion has its own way home',()=>{
 const room=scene(.24),e=room.simulation.spawn('codex-companion'),idle=codexLife(room,e);e.position={...idle.home};
 const visitor=room.simulation.spawn('pat');visitor.position={...idle.home,x:idle.home.x+2};run(room,idle,1);
 assert.equal(e.gesture?.kind,'wave');assert.ok(PERSONAS.codex.lines.includes(e.speech));
 assert.notEqual(PERSONAS.codex.homeLine,PERSONAS.claude.homeLine,'no more "Heading home to Clover Rise!" from Codex');
 assert.equal(PERSONAS.claude.night,'sleep');
});
const tempRoom=t=>{const dir=mkdtempSync(join(tmpdir(),'sky-life-'));t.after(()=>rmSync(dir,{recursive:true,force:true}));return new Room(dir);};
test('goal lists are bounded, cleaned and saved with the world',t=>{
 const room=tempRoom(t),sent=[];room.sendAll=m=>sent.push(m);
 goalsFor(room).set('claude-companion',['  Stock the   stockpile ','Stock the stockpile',...Array.from({length:9},(_,i)=>`goal ${i} `+'x'.repeat(200)),42]);
 const list=goalsFor(room).list('claude-companion');assert.equal(list.length,GOAL_LIMIT);assert.equal(list[0],'Stock the stockpile');assert.ok(list.every(g=>g.length<=80));
 assert.equal(sent.at(-1).type,'goals','players see the change');
 room.save();assert.deepEqual(goalsFor(new Room(room.directory)).list('claude-companion'),list);
 const reply=parseReflection('Sure! {"goals":["Map Lookout Rock"],"message":"","action":{"type":"breakBlock","pos":{"x":1,"y":2,"z":3}}}');
 assert.deepEqual(reply,{goals:['Map Lookout Rock'],message:'',action:null},'a reflection can never edit blocks');
 assert.deepEqual(parseReflection('{"goals":[],"action":{"type":"emote","name":"wave"}}').action,{type:'emote',name:'wave'});
});
test('a reflection updates goals and may speak; it needs a person on the island',async t=>{
 const room=tempRoom(t);room.chat=new WorldChat(room);const trace=[];room.trace=(type,f)=>trace.push({type,...f});
 const agent=new Companion(room,process.cwd(),PERSONAS.claude);let calls=0,next='';
 agent.think=async payload=>{calls++;assert.equal(payload.mode,'reflect');assert.equal(payload.image,null);return next;};
 agent.lastReflect=0;agent.considerReflecting();await new Promise(r=>setImmediate(r));
 assert.equal(calls,0,'nobody online: no model call');
 const pat=room.simulation.spawn('pat'),home=room.simulation.entities.get('claude-companion').position;room.clients.set({},{entity:pat});
 pat.position={x:home.x+60,y:home.y,z:home.z};
 next='{"goals":["Visit Sam on Origin Island"],"message":"Nobody is near enough to hear this.","action":null}';
 await agent.reflect('a quiet moment');
 assert.deepEqual(goalsFor(room).list('claude-companion'),['Visit Sam on Origin Island']);
 assert.ok(!room.chat.entries.some(e=>e.text==='Nobody is near enough to hear this.'),'no one within 20 blocks: goals change, nothing is said');
 pat.position={x:home.x+3,y:home.y,z:home.z};
 next='{"goals":["Visit Sam on Origin Island"],"message":"I think I will visit Sam soon.","action":{"type":"goto","place":"Atlantis"}}';
 await agent.reflect('a quiet moment');
 assert.equal(room.chat.entries.at(-1).text,'I think I will visit Sam soon.');
 next='{"goals":["Visit Sam on Origin Island"],"message":"Talking again so soon.","action":null}';await agent.reflect('a quiet moment');
 assert.ok(!room.chat.entries.some(e=>e.text==='Talking again so soon.'),'at most one reflection line per 30 minutes');
 assert.ok(trace.some(r=>r.type==='companion.refused'),'an unknown place is refused, not crashed on');assert.equal(agent.active,null,'the run ends cleanly');
 next='not json at all';await agent.reflect('night has fallen');
 assert.equal(agent.active,null);assert.deepEqual(goalsFor(room).list('claude-companion'),['Visit Sam on Origin Island'],'a bad reply changes nothing');
});
